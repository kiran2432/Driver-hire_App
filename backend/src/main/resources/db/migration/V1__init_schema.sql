-- Driver Hire: initial schema (portable across PostgreSQL and H2 in PostgreSQL mode)

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    full_name     VARCHAR(120) NOT NULL,
    phone         VARCHAR(20)  NOT NULL,
    role          VARCHAR(20)  NOT NULL,
    enabled       BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_users_email UNIQUE (email),
    CONSTRAINT ck_users_role CHECK (role IN ('DRIVER', 'CUSTOMER'))
);

CREATE TABLE driver_profiles (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT        NOT NULL,
    address             VARCHAR(255)  NOT NULL,
    city                VARCHAR(100)  NOT NULL,
    state               VARCHAR(100)  NOT NULL,
    years_of_experience INT           NOT NULL,
    license_number      VARCHAR(50)   NOT NULL,
    license_expiry      DATE          NOT NULL,
    drives_manual       BOOLEAN       NOT NULL DEFAULT TRUE,
    drives_automatic    BOOLEAN       NOT NULL DEFAULT TRUE,
    languages           VARCHAR(255),
    bio                 VARCHAR(1000),
    daily_rate          NUMERIC(10,2) NOT NULL,
    available           BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_driver_profiles_user UNIQUE (user_id),
    CONSTRAINT fk_driver_profiles_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_driver_experience CHECK (years_of_experience >= 0 AND years_of_experience <= 60),
    CONSTRAINT ck_driver_rate CHECK (daily_rate >= 0)
);

CREATE INDEX idx_driver_profiles_city_available ON driver_profiles (city, available);

CREATE TABLE customer_profiles (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL,
    address    VARCHAR(255) NOT NULL,
    city       VARCHAR(100) NOT NULL,
    state      VARCHAR(100) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_customer_profiles_user UNIQUE (user_id),
    CONSTRAINT fk_customer_profiles_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE TABLE trips (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id       BIGINT       NOT NULL,
    driver_profile_id BIGINT,
    pickup_city       VARCHAR(100) NOT NULL,
    pickup_location   VARCHAR(255) NOT NULL,
    destination       VARCHAR(255) NOT NULL,
    trip_type         VARCHAR(20)  NOT NULL,
    start_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    return_at         TIMESTAMP WITH TIME ZONE,
    car_make          VARCHAR(60)  NOT NULL,
    car_model         VARCHAR(60)  NOT NULL,
    car_type          VARCHAR(20)  NOT NULL,
    transmission      VARCHAR(20)  NOT NULL,
    notes             VARCHAR(1000),
    status            VARCHAR(20)  NOT NULL,
    version           BIGINT       NOT NULL DEFAULT 0,
    created_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at        TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_trips_customer FOREIGN KEY (customer_id) REFERENCES users (id),
    CONSTRAINT fk_trips_driver FOREIGN KEY (driver_profile_id) REFERENCES driver_profiles (id),
    CONSTRAINT ck_trips_type CHECK (trip_type IN ('ONE_WAY', 'ROUND_TRIP')),
    CONSTRAINT ck_trips_car_type CHECK (car_type IN ('HATCHBACK', 'SEDAN', 'SUV', 'MUV', 'LUXURY')),
    CONSTRAINT ck_trips_transmission CHECK (transmission IN ('MANUAL', 'AUTOMATIC')),
    CONSTRAINT ck_trips_status CHECK (status IN ('OPEN', 'REQUESTED', 'CONFIRMED', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT ck_trips_return CHECK (
        (trip_type = 'ONE_WAY' AND return_at IS NULL) OR
        (trip_type = 'ROUND_TRIP' AND return_at IS NOT NULL AND return_at > start_at)
    )
);

CREATE INDEX idx_trips_status_city ON trips (status, pickup_city);
CREATE INDEX idx_trips_customer ON trips (customer_id);
CREATE INDEX idx_trips_driver ON trips (driver_profile_id);

CREATE TABLE refresh_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL,
    token_hash VARCHAR(64) NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked    BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_refresh_tokens_hash UNIQUE (token_hash),
    CONSTRAINT fk_refresh_tokens_user FOREIGN KEY (user_id) REFERENCES users (id)
);

CREATE INDEX idx_refresh_tokens_user ON refresh_tokens (user_id);
